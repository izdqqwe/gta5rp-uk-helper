  function smartSearch(text, seen, limit = 4) {
    return Object.keys(ARTICLES)
      .filter((id) => !seen.has(id))
      .map((id) => [id, scoreArticle(text, id)])
      .filter(([, s]) => s >= 1)
      .sort((a, b) => b[1] - a[1])
      .slice(0, limit);
  }

  function buildRpText(articles) {
    if (!articles.length) return "";
    const law = articles.filter((a) => a.code === "FIB");
    const ustav = articles.filter((a) => a.code === "FIB-U");
    const lines = [];
    if (law.length) {
      lines.push("По Закону о ФРБ применимо:");
      law.forEach((a) => lines.push(`- ${a.label} — ${a.title};`));
    }
    if (ustav.length) {
      if (lines.length) lines.push("");
      lines.push("По Уставу FIB применимо:");
      ustav.forEach((a) => lines.push(`- ${a.label} — ${a.title};`));
    }
    if (lines.length) lines[lines.length - 1] = lines[lines.length - 1].replace(/;$/, ".");
    return lines.join("\n");
  }

  window.analyzeFib = function analyzeFib(text) {
    const clauses = text.trim().split(/[+;,]|\s+и\s+|\n/).map((p) => p.trim()).filter(Boolean);
    const allTags = new Set();
    const matched = [];
    const seen = new Set();
    const warnings = [];
    let usedSmartSearch = false;

    for (const clause of (clauses.length ? clauses : [text.trim()])) {
      const tags = detectTags(clause);
      tags.forEach((t) => allTags.add(t));
      const noRules = applyRules(clause, tags, matched, seen);
      if (noRules) {
        for (const [id, score] of smartSearch(clause, seen, 2)) {
          seen.add(id);
          matched.push(makeArticle(id, `Подобрано по смыслу: «${clause}» (score ${score.toFixed(1)})`, true));
          usedSmartSearch = true;
        }
      }
    }

    if (!matched.length) {
      for (const [id, score] of smartSearch(text, new Set(), 4)) {
        seen.add(id);
        matched.push(makeArticle(id, `Подобрано по смыслу (score ${score.toFixed(1)})`, true));
        usedSmartSearch = true;
      }
    }

    if (usedSmartSearch) {
      warnings.unshift("Часть статей подобрана умным поиском — проверь по тексту Закона о ФРБ и Устава FIB.");
    }
    if (!matched.length) {
      warnings.push("Опиши: действия FIB, устав (патруль, бейдж, видео, выговоры), задержание, оружие, оцепление, досмотр, IB.");
    }

    return {
      code: "FIB",
      tags: [...allTags].sort(),
      warnings,
      maxStars: 0,
      totalYears: 0,
      cappedYears: 0,
      rpText: buildRpText(matched),
      articles: matched,
    };
  };
